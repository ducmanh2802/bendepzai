export function getCompetitionQuestionById(id: string): CompetitionQuestion | undefined {
  return COMPETITION_QUESTIONS.find((q) => q.id === id);
}

export function getQuestionsBySubject(subject: string): CompetitionQuestion[] {
  return COMPETITION_QUESTIONS.filter((q) => q.subject === subject);
}

export function getQuestionsBySkill(skillId: string): CompetitionQuestion[] {
  return COMPETITION_QUESTIONS.filter((q) => q.skillId === skillId);
}

export function getQuestionsByTopic(topic: string): CompetitionQuestion[] {
  return COMPETITION_QUESTIONS.filter((q) => q.topic === topic);
}

export function getQuestionsByQuestionType(type: string): CompetitionQuestion[] {
  return COMPETITION_QUESTIONS.filter((q) => q.questionType === type);
}

/** Distinct topics present in the bank (used by the coverage matrix, §16). */
export function getAllTopics(): string[] {
  return Array.from(new Set(COMPETITION_QUESTIONS.map((q) => q.topic)));
}

export function getAllQuestionTypes(): string[] {
  return Array.from(new Set(COMPETITION_QUESTIONS.map((q) => q.questionType)));
}
