const HINT_PATTERN = 'Nhìn bước nhảy giữa hai số liền nhau.';
const HINT_LINE = 'Đếm các vạch trên tia số rồi tìm ô trống.';

/** Câu có tia số với ô trống (visual NumberLine). */
function missingNumberQuestion(
  id: string,
  prompt: string,
  options: string[],
  correct: string,
  line: { start: number; end: number; step: number; missing: number },
  difficulty: 1 | 2 | 3
): ReturnType<typeof mathQ> {
  return mathQ(TOPIC, {
    id,
    skillId: 'math_missing_number',
    difficulty,
    type: 'image-choice',
    prompt,
    options,
    correctAnswer: correct,
    hint: HINT_LINE,
    explanation: `Ô trống là số ${correct}.`,
    visual: { kind: 'NumberLine', props: { ...line } },
  });
}

